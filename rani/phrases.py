def render(key: str, lang: str = "ur", **kw) -> tuple[str, str]:
    """Return (display, speech) for a phrase key."""
    table = P.get(lang) or P["ur"]
    disp_t, speech_t = table.get(key) or P["ur"].get(key) or table["error"]
    app = kw.get("app")
    if app:
        kw.setdefault("app_u", APP_URDU.get(str(app).lower().replace(" ", ""), app))
    if "plug" in kw and lang == "ur":
        kw["plug_u"] = P["ur"]["plug_on" if kw.get("plugged") else "plug_off"][1]
        kw["plug"] = P["ur"]["plug_on" if kw.get("plugged") else "plug_off"][0]
    elif "plug" in kw:
        kw["plug"] = P["en"]["plug_on" if kw.get("plugged") else "plug_off"][0]
    if "gpu" in kw:
        kw.setdefault("gpu_u", kw["gpu"])
    if "engine" in kw:
        kw.setdefault("engine_u", {"google": "گوگل", "youtube": "یوٹیوب"}.get(kw["engine"].lower(), kw["engine"]))

    class _D(dict):
        def __missing__(self, k):
            return ""
    d = _D(kw)
    return disp_t.format_map(d), speech_t.format_map(d)
